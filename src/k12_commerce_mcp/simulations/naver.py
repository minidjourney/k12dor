_OPERATIONS: tuple[DisabledOperation, ...] = tuple(_operation(row) for row in _ROWS)
_BY_ID = {item.operation_id: item for item in _OPERATIONS}
if len(_BY_ID) != len(_OPERATIONS):
    raise RuntimeError("duplicate naver operation id")


def list_disabled_operations() -> tuple[DisabledOperation, ...]:
    return _OPERATIONS


def official_source_counts() -> dict[str, object]:
    methods = Counter(item.method for item in _OPERATIONS)
    reasons = Counter(item.disabled_reason for item in _OPERATIONS)
    enabled = sum(1 for item in _OPERATIONS if item.execution_enabled)
    return {
        "snapshot_id": SNAPSHOT_ID,
        "html_files": _HTML_FILES,
        "operations": len(_OPERATIONS),
        "non_operations": _NON_OPERATIONS,
        "disabled_operations": len(_OPERATIONS) - enabled,
        "enabled_operations": enabled,
        "by_method": dict(sorted(methods.items())),
        "by_disabled_reason": dict(sorted(reasons.items())),
        "heuristic_used_as_safety_judgment": False,
        "knowledge_status": "snapshot_not_confirmed",
        "post_snapshot_document_change": "unknown",
    }


def _require(operation_id: str) -> DisabledOperation:
    found = _BY_ID.get(operation_id)
    if found is None:
        raise DisabledSimulationError("naver operation remains disabled")
    return found


def simulate(operation_id: str, transport: object | None = None) -> SimulationResult:
    """Return a disabled result. transport is accepted and never called."""

    operation = _require(operation_id)
    return SimulationResult(operation_id=operation.operation_id)


def propose_post_approval(operation_id: str) -> PostApprovalProposal:
    """Suggest the documented method and path. This does not enable the operation."""

    operation = _require(operation_id)
    return PostApprovalProposal(
        operation_id=operation.operation_id,
        proposed_method=operation.method,
        proposed_path=operation.path,
        document_ref=operation.document_ref,
    )


def activate(operation_id: str) -> None:
    """Refuse activation, including ids outside the official capture."""

    _require(operation_id)
    raise DisabledSimulationError("naver operation remains disabled")
